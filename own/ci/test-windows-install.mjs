import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
if(process.platform!=='win32')throw Error('Windows runner required');
const [archive,manifestFile]=process.argv.slice(2).map(p=>path.resolve(p));
const fixture=fs.mkdtempSync(path.join(os.tmpdir(),'own-install-'));
const env={...process.env,LOCALAPPDATA:path.join(fixture,'Local'),APPDATA:path.join(fixture,'Roaming')};
const original=path.join(env.LOCALAPPDATA,'Programs','Codex','sentinel.txt');
fs.mkdirSync(path.dirname(original),{recursive:true});fs.writeFileSync(original,'original-installation',{flag:'wx'});
const npm=(args,options={})=>execFileSync('npm',args,{shell:true,encoding:'utf8',env,...options});
const packed=JSON.parse(npm(['pack','--json','--pack-destination',fixture],{cwd:path.resolve('own')}))[0];
npm(['install','--prefix',path.join(fixture,'manager'),path.join(fixture,packed.filename),'--ignore-scripts','--omit=dev']);
const cli=path.join(fixture,'manager','node_modules','@petercjl','codex-own','bin','codex-own.mjs');
const run=(...args)=>JSON.parse(execFileSync(process.execPath,[cli,...args],{env,encoding:'utf8'}));
const result=run('install','--archive',archive,'--manifest',manifestFile,'--yes');
assert.equal(result.version,JSON.parse(fs.readFileSync(manifestFile)).version);
assert.equal(result.target,path.join(env.LOCALAPPDATA,'Programs','codex-own','current'));
assert.ok(fs.existsSync(path.join(result.target,'codex-own.exe')));
const link=path.join(env.APPDATA,'Microsoft','Windows','Start Menu','Programs','codex-own','codex-own.lnk');
assert.ok(fs.statSync(link).size>0);
const keyFile=path.join(fixture,'test-key.txt');fs.writeFileSync(keyFile,'sk-fixture-only-no-service-access',{flag:'wx'});
run('configure','--api-key-file',keyFile,'--yes');
const core=path.join(env.LOCALAPPDATA,'codex-own-independent','core');
assert.equal(JSON.parse(fs.readFileSync(path.join(core,'auth.json'))).auth_mode,'apikey');
const config=fs.readFileSync(path.join(core,'config.toml'));
assert.match(config.toString(),/dashscope_deepseek/);
const second=run('configure','--api-key-file',keyFile,'--yes');
assert.ok(fs.existsSync(second.backup));assert.deepEqual(fs.readFileSync(path.join(core,'config.toml')),config);
assert.equal(fs.readFileSync(original,'utf8'),'original-installation');
assert.equal(run('doctor').ok,true);
console.log(JSON.stringify({ok:true,packedInstaller:true,windowsShortcut:true,independentConfig:true,originalPreserved:true,guiTested:false}));
